//! Python-compatible text formatting (core contract). Messages, ETags and Prometheus output embed Python's own
//! renderings of floats and strings; these helpers reproduce them exactly so the Rust backend answers byte for byte
//! where it matters.
//!
//! * `float_repr`: `repr(float)` / `str(float)` (shortest round-trip digits, `.0` on integers, exponent outside
//!   1e-4 <= |x| < 1e16, at least two exponent digits).
//! * `str_repr`: `repr(str)` (quotes chosen like CPython, escapes for `\\ \n \r \t` and non-printables).
//! * `list_repr`: `repr(list[str])`, e.g. `['15m', '1h', '24h']`.
//! * `go_float`: `prometheus_client.utils.floatToGoString`.
//! * `char_prefix` / `char_len`: Python slicing and `len()` count characters (code points), never bytes.

/// `repr(x)` for a Python float.
#[must_use]
pub fn float_repr(x: f64) -> String {
    if x.is_nan() {
        return "nan".to_owned();
    }
    if x.is_infinite() {
        return if x > 0.0 {
            "inf".to_owned()
        } else {
            "-inf".to_owned()
        };
    }
    if x == 0.0 {
        return if x.is_sign_negative() {
            "-0.0".to_owned()
        } else {
            "0.0".to_owned()
        };
    }
    // CPython's repr = the SHORTEST digit count that round-trips, and among the candidates of that length the one
    // NEAREST the exact value, ties to even (dtoa mode 0). Rust's `{:e}` gives the right length but can pick the other
    // candidate on a tie (-1133092563735992.25 -> ...2.3 instead of ...2.2), so the digits come from the correctly
    // rounded fixed-precision form at that length.
    let shortest = format!("{:e}", x.abs());
    let n = shortest
        .split_once('e')
        .map_or(1, |(m, _)| m.chars().filter(char::is_ascii_digit).count());
    let sci = format!("{:.*e}", n.saturating_sub(1), x.abs());
    let sci = if sci.parse::<f64>().ok() == Some(x.abs()) {
        sci
    } else {
        shortest
    };
    let (mant, exp) = sci.split_once('e').unwrap_or((sci.as_str(), "0"));
    let digits: String = mant.chars().filter(char::is_ascii_digit).collect();
    let exp: i32 = exp.parse().unwrap_or(0);
    let decpt = exp + 1; // value = 0.DIGITS x 10^decpt
    let sign = if x < 0.0 { "-" } else { "" };
    let n = i32::try_from(digits.len()).unwrap_or(i32::MAX);
    if decpt <= -4 || decpt > 16 {
        let (first, rest) = digits.split_at(1);
        let e = decpt - 1;
        let es = if e < 0 {
            format!("-{:02}", -e)
        } else {
            format!("+{e:02}")
        };
        if rest.is_empty() {
            format!("{sign}{first}e{es}")
        } else {
            format!("{sign}{first}.{rest}e{es}")
        }
    } else if decpt <= 0 {
        let zeros = "0".repeat(usize::try_from(-decpt).unwrap_or(0));
        format!("{sign}0.{zeros}{digits}")
    } else if decpt >= n {
        let zeros = "0".repeat(usize::try_from(decpt - n).unwrap_or(0));
        format!("{sign}{digits}{zeros}.0")
    } else {
        let (a, b) = digits.split_at(usize::try_from(decpt).unwrap_or(0));
        format!("{sign}{a}.{b}")
    }
}

/// `prometheus_client.utils.floatToGoString`.
#[must_use]
pub fn go_float(d: f64) -> String {
    if d == f64::INFINITY {
        return "+Inf".to_owned();
    }
    if d == f64::NEG_INFINITY {
        return "-Inf".to_owned();
    }
    if d.is_nan() {
        return "NaN".to_owned();
    }
    let s = float_repr(d);
    if let Some(dot) = s.find('.')
        && d > 0.0
        && dot > 6
    {
        let mut mantissa = format!("{}.{}{}", &s[..1], &s[1..dot], &s[dot + 1..]);
        while mantissa.ends_with('0') || mantissa.ends_with('.') {
            mantissa.pop();
        }
        return format!("{mantissa}e+0{}", dot - 1);
    }
    s
}

/// `repr(s)` for a Python str: CPython's quoting and escapes, with the exact `str.isprintable()` table of CPython
/// 3.13 (Unicode 15.1.0; services/pyyaml/pyunicode.rs, generated by parity/gen/gen_unicode_tables.py).
#[must_use]
pub fn str_repr(s: &str) -> String {
    crate::services::pyyaml::pyunicode::repr(s)
}

/// `repr(list_of_str)`, e.g. `['15m', '1h']`.
#[must_use]
pub fn list_repr<S: AsRef<str>>(items: &[S]) -> String {
    let inner: Vec<String> = items.iter().map(|s| str_repr(s.as_ref())).collect();
    format!("[{}]", inner.join(", "))
}

/// Python `len(s)`: code points.
#[must_use]
pub fn char_len(s: &str) -> usize {
    s.chars().count()
}

/// Python `s[:n]`: the first `n` code points.
#[must_use]
pub fn char_prefix(s: &str, n: usize) -> &str {
    match s.char_indices().nth(n) {
        Some((i, _)) => &s[..i],
        None => s,
    }
}

/// Python `s[n:]`: everything after the first `n` code points.
#[must_use]
pub fn char_suffix_from(s: &str, n: usize) -> &str {
    match s.char_indices().nth(n) {
        Some((i, _)) => &s[i..],
        None => "",
    }
}

/// Options of Python's `json.dumps` that the console uses.
#[derive(Debug, Clone, Copy)]
pub struct JsonOpts {
    /// `indent=N` (None: one line with `", "` / `": "` separators).
    pub indent: Option<usize>,
    pub sort_keys: bool,
    pub ensure_ascii: bool,
}

impl Default for JsonOpts {
    fn default() -> Self {
        JsonOpts {
            indent: None,
            sort_keys: false,
            ensure_ascii: true,
        }
    }
}

/// `json.dumps(value)` with Python's defaults (ensure_ascii, `", "` and `": "` separators, float repr).
#[must_use]
pub fn json_dumps(v: &serde_json::Value) -> String {
    json_dumps_with(v, JsonOpts::default())
}

/// `json.dumps(value, indent=..., sort_keys=..., ensure_ascii=...)`.
#[must_use]
pub fn json_dumps_with(v: &serde_json::Value, o: JsonOpts) -> String {
    let mut out = String::new();
    dump(v, o, 0, &mut out);
    out
}

fn dump_str(s: &str, ascii: bool, out: &mut String) {
    out.push('"');
    for c in s.chars() {
        match c {
            '"' => out.push_str("\\\""),
            '\\' => out.push_str("\\\\"),
            '\n' => out.push_str("\\n"),
            '\r' => out.push_str("\\r"),
            '\t' => out.push_str("\\t"),
            '\u{8}' => out.push_str("\\b"),
            '\u{c}' => out.push_str("\\f"),
            c if u32::from(c) < 0x20 => out.push_str(&format!("\\u{:04x}", u32::from(c))),
            c if ascii && u32::from(c) > 0x7e => {
                let mut buf = [0u16; 2];
                for u in c.encode_utf16(&mut buf) {
                    out.push_str(&format!("\\u{u:04x}"));
                }
            }
            c => out.push(c),
        }
    }
    out.push('"');
}

fn dump(v: &serde_json::Value, o: JsonOpts, level: usize, out: &mut String) {
    use serde_json::Value;
    let (item_sep, key_sep) = if o.indent.is_some() {
        (",", ": ")
    } else {
        (", ", ": ")
    };
    let newline = |out: &mut String, lvl: usize| {
        if let Some(n) = o.indent {
            out.push('\n');
            out.push_str(&" ".repeat(n * lvl));
        }
    };
    match v {
        Value::Null => out.push_str("null"),
        Value::Bool(b) => out.push_str(if *b { "true" } else { "false" }),
        Value::Number(n) => {
            if n.is_f64() {
                let f = n.as_f64().unwrap_or(0.0);
                if f.is_nan() {
                    out.push_str("NaN");
                } else if f.is_infinite() {
                    out.push_str(if f > 0.0 { "Infinity" } else { "-Infinity" });
                } else {
                    out.push_str(&float_repr(f));
                }
            } else {
                out.push_str(&n.to_string());
            }
        }
        Value::String(s) => dump_str(s, o.ensure_ascii, out),
        Value::Array(a) => {
            if a.is_empty() {
                out.push_str("[]");
                return;
            }
            out.push('[');
            for (i, item) in a.iter().enumerate() {
                if i > 0 {
                    out.push_str(item_sep);
                }
                newline(out, level + 1);
                dump(item, o, level + 1, out);
            }
            newline(out, level);
            out.push(']');
        }
        Value::Object(m) => {
            if m.is_empty() {
                out.push_str("{}");
                return;
            }
            let mut keys: Vec<&String> = m.keys().collect();
            if o.sort_keys {
                keys.sort();
            }
            out.push('{');
            for (i, k) in keys.into_iter().enumerate() {
                if i > 0 {
                    out.push_str(item_sep);
                }
                newline(out, level + 1);
                dump_str(k, o.ensure_ascii, out);
                out.push_str(key_sep);
                if let Some(val) = m.get(k) {
                    dump(val, o, level + 1, out);
                }
            }
            newline(out, level);
            out.push('}');
        }
    }
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn float_repr_matches_cpython() {
        for (x, want) in [
            (5.0, "5.0"),
            (1e16, "1e+16"),
            (1e15, "1000000000000000.0"),
            (0.0001, "0.0001"),
            (1e-5, "1e-05"),
            (123_456_789_012_345_680.0, "1.2345678901234568e+17"),
            (-0.0, "-0.0"),
            (2.5e-7, "2.5e-07"),
            (1_793_138_911.163_925_4, "1793138911.1639254"),
            (0.1, "0.1"),
            (-1.5, "-1.5"),
            (0.95, "0.95"),
            (f64::INFINITY, "inf"),
        ] {
            assert_eq!(float_repr(x), want, "{x}");
        }
    }

    /// CPython's repr of 9000+ doubles incl. decimal ties (round-half-to-even), parity/gen/gen_float_repr_golden.py.
    #[test]
    fn float_repr_matches_cpython_golden() {
        let golden = include_str!("../../tests/fixtures/pyfmt/float_repr.txt");
        let mut bad = Vec::new();
        for line in golden.lines() {
            let (hex, want) = line.split_once(' ').unwrap();
            let x = f64::from_bits(u64::from_str_radix(hex, 16).unwrap());
            if float_repr(x) != want {
                bad.push(format!("{hex}: {} != {want}", float_repr(x)));
            }
        }
        assert!(
            bad.is_empty(),
            "{} mismatches, e.g. {:?}",
            bad.len(),
            &bad[..bad.len().min(5)]
        );
    }

    #[test]
    fn go_float_matches_prometheus_client() {
        assert_eq!(go_float(1.0), "1.0");
        assert_eq!(go_float(5.0), "5.0");
        assert_eq!(go_float(0.0123), "0.0123");
        assert_eq!(go_float(f64::INFINITY), "+Inf");
        assert_eq!(go_float(1_793_138_911.163_925_4), "1.7931389111639254e+09");
        assert_eq!(go_float(1_234_567.0), "1.234567e+06");
    }

    #[test]
    fn str_repr_matches_cpython() {
        assert_eq!(str_repr("nope"), "'nope'");
        assert_eq!(str_repr("it's"), "\"it's\"");
        assert_eq!(str_repr("a\nb\\"), "'a\\nb\\\\'");
        assert_eq!(str_repr("\x00"), "'\\x00'");
        assert_eq!(list_repr(&["15m", "1h", "24h"]), "['15m', '1h', '24h']");
    }

    #[test]
    fn json_dumps_matches_python() {
        let v = serde_json::json!({"a": 1, "b": [1.0, "é\n", null], "c": {}});
        assert_eq!(
            json_dumps(&v),
            r#"{"a": 1, "b": [1.0, "\u00e9\n", null], "c": {}}"#
        );
        let pretty = json_dumps_with(
            &serde_json::json!({"k": [1, 2]}),
            JsonOpts {
                indent: Some(2),
                ..JsonOpts::default()
            },
        );
        assert_eq!(pretty, "{\n  \"k\": [\n    1,\n    2\n  ]\n}");
    }

    #[test]
    fn char_slicing_counts_code_points() {
        assert_eq!(char_prefix("héllo", 2), "hé");
        assert_eq!(char_len("héllo"), 5);
        assert_eq!(char_suffix_from("héllo", 2), "llo");
    }
}
